#!/usr/bin/env python3
"""Convert BDF bitmap fonts into C tables for zimwiki.

  bdf2c.py fontlist.txt fonts.c fonts_gen.h      built-in fonts
  bdf2c.py --bin FONT.bdf OUT.BIN                fallback font file for the SD card

Glyph record (both forms): u16 code point (BMP only), u8 advance,
i8 x offset, i8 top (rows above the baseline), u8 width, u8 height,
u8 pad, u32 bitmap offset.  Bitmap rows are ceil(width/8) bytes, MSB is
the leftmost pixel.
"""
import os
import struct
import sys


def parse_bdf(path):
    glyphs = {}
    ascent = descent = None
    with open(path, encoding="latin-1") as f:
        lines = f.read().splitlines()
    i = 0
    while i < len(lines):
        ln = lines[i]
        if ln.startswith("FONT_ASCENT "):
            ascent = int(ln.split()[1])
        elif ln.startswith("FONT_DESCENT "):
            descent = int(ln.split()[1])
        elif ln.startswith("STARTCHAR"):
            enc = adv = None
            bbx = None
            rows = []
            i += 1
            while not lines[i].startswith("ENDCHAR"):
                l2 = lines[i]
                if l2.startswith("ENCODING "):
                    enc = int(l2.split()[1])
                elif l2.startswith("DWIDTH "):
                    adv = int(l2.split()[1])
                elif l2.startswith("BBX "):
                    bbx = [int(v) for v in l2.split()[1:5]]
                elif l2 == "BITMAP":
                    i += 1
                    while not lines[i].startswith("ENDCHAR"):
                        rows.append(lines[i].strip())
                        i += 1
                    break
                i += 1
            if enc is not None and 0 <= enc <= 0xFFFF and bbx and adv is not None:
                w, h, xo, yo = bbx
                nb = (w + 7) // 8
                data = bytearray()
                for r in rows[:h]:
                    v = bytes.fromhex(r.ljust(nb * 2, "0")[: nb * 2]) if r else bytes(nb)
                    data += v
                data += bytes(nb * (h - len(rows[:h])))
                # trim blank rows to save space
                top = yo + h
                while h and not any(data[:nb]):
                    data = data[nb:]
                    h -= 1
                    top -= 1
                while h and not any(data[-nb:]):
                    data = data[:-nb]
                    h -= 1
                if h == 0:
                    w = 0
                    data = bytearray()
                glyphs[enc] = (adv, xo, top, w, h, bytes(data))
        i += 1
    if ascent is None:
        ascent = max((g[2] for g in glyphs.values()), default=10)
    if descent is None:
        descent = 3
    return ascent, descent, glyphs


def clamp8(v):
    return max(-128, min(127, v))


def tighten(glyphs):
    """cap the gap after a glyph at one pixel (the bold BDFs have
    lower case letters with two or three blank columns)"""
    for cp, (adv, xo, top, w, h, data) in list(glyphs.items()):
        if w and cp > 32 and adv > xo + w + 1:
            glyphs[cp] = (xo + w + 1, xo, top, w, h, data)


def pack(ascent, descent, glyphs):
    recs = bytearray()
    bits = bytearray()
    for cp in sorted(glyphs):
        adv, xo, top, w, h, data = glyphs[cp]
        recs += struct.pack("<HBbbBBBI", cp, min(adv, 255), clamp8(xo), clamp8(top),
                            w, h, 0, len(bits))
        bits += data
    return recs, bits


def main():
    if sys.argv[1] == "--bin":
        a, d, g = parse_bdf(sys.argv[2])
        recs, bits = pack(a, d, g)
        with open(sys.argv[3], "wb") as f:
            f.write(b"ZWFT")
            f.write(struct.pack("<IBBH", len(g), a, d, 0))
            f.write(recs)
            f.write(bits)
        print("%s: %d glyphs, %d bytes" % (sys.argv[3], len(g), 12 + len(recs) + len(bits)))
        return

    listfile, out_c, out_h = sys.argv[1:4]
    base = os.path.dirname(os.path.abspath(listfile))
    fonts = []
    for ln in open(listfile):
        ln = ln.split("#")[0].strip()
        if not ln:
            continue
        parts = ln.split(None, 2)
        fonts.append((parts[0], os.path.join(base, parts[1]),
                      len(parts) > 2 and "[tight]" in parts[2]))

    h = ["/* generated by tools/bdf2c.py - do not edit */",
         "#ifndef FONTS_GEN_H", "#define FONTS_GEN_H", "enum {"]
    for i, (name, _, _t) in enumerate(fonts):
        h.append("\tFONT_%s = %d," % (name, i))
    h += ["\tFONT_COUNT = %d" % len(fonts), "};", "#endif", ""]
    open(out_h, "w").write("\n".join(h))

    c = ["/* generated by tools/bdf2c.py - do not edit */",
         '#include "font.h"', ""]
    total = 0
    for name, path, tight in fonts:
        a, d, g = parse_bdf(path)
        if tight:
            tighten(g)
        recs, bits = pack(a, d, g)
        total += len(recs) + len(bits)
        lname = name.lower()
        c.append("static const uint8_t %s_glyphs[] = {" % lname)
        for i in range(0, len(recs), 24):
            c.append("\t" + ",".join(str(b) for b in recs[i:i + 24]) + ",")
        c.append("};")
        c.append("static const uint8_t %s_bits[] = {" % lname)
        for i in range(0, len(bits), 32):
            c.append("\t" + ",".join(str(b) for b in bits[i:i + 32]) + ",")
        if not bits:
            c.append("\t0")
        c.append("};")
        c.append("")
        fonts_meta = (lname, len(g), a, d)
        c.append("#define %s_META %s_glyphs, %s_bits, %d, %d, %d" %
                 (name, lname, lname, len(g), a, d))
    c.append("font_t fonts[FONT_COUNT] = {")
    for name, _, _t in fonts:
        c.append("\t{ %s_META, 0 }," % name)
    c.append("};")
    open(out_c, "w").write("\n".join(c) + "\n")
    print("fonts: %d fonts, %d bytes of tables" % (len(fonts), total))


if __name__ == "__main__":
    main()
