#!/usr/bin/env python3
"""Generate src/fold_table.h: search folding for titles and queries.

Each mapped code point becomes its lower-case, accent-free form, so
typing "eclair" finds "Éclair", "muller" finds "Müller", "ss" finds
"Straße".  Dashes become spaces and apostrophes vanish, so "rock n roll"
finds "Rock 'n' roll".  ASCII is handled in code; this table covers the
rest of the Basic Multilingual Plane where folding changes anything.
"""
import sys
import unicodedata

SPACE_LIKE = set("‐‑‒–—―−    　")
DROP = set("‘’‛ʼʻ´`′­​‌‍⁠﻿")
# letters without a Unicode decomposition that people type as ASCII
MANUAL = {"æ": "ae", "Æ": "ae", "ø": "o", "Ø": "o", "ł": "l", "Ł": "l",
          "đ": "d", "Đ": "d", "ð": "d", "Ð": "d", "þ": "th", "Þ": "th",
          "œ": "oe", "Œ": "oe", "ı": "i", "ħ": "h", "Ħ": "h", "ŧ": "t", "Ŧ": "t"}
QUOTE_LIKE = {"“": '"', "”": '"', "„": '"', "«": '"', "»": '"'}


def fold(ch):
    if ch in SPACE_LIKE:
        return " "
    if ch in DROP:
        return ""
    if ch in MANUAL:
        return MANUAL[ch]
    if ch in QUOTE_LIKE:
        return QUOTE_LIKE[ch]
    cat = unicodedata.category(ch)
    if cat in ("Mn", "Me"):
        return ""          # combining marks
    if cat in ("Cs", "Co", "Cn"):
        return None
    d = unicodedata.normalize("NFKD", ch)
    d = "".join(c for c in d if unicodedata.category(c) not in ("Mn", "Me"))
    d = d.casefold()
    # keep compatibility mappings that stay short and printable
    if not d or len(d) > 3 or any(unicodedata.category(c).startswith("C") for c in d):
        d = unicodedata.normalize("NFD", ch)
        d = "".join(c for c in d if unicodedata.category(c) not in ("Mn", "Me")).casefold()
    if " " in d and ch not in SPACE_LIKE:
        return None
    return d


def main():
    rows = []
    for cp in range(0x80, 0x10000):
        ch = chr(cp)
        f = fold(ch)
        if f is None or f == ch:
            continue
        b = f.encode("utf-8")
        if len(b) > 6:
            continue
        rows.append((cp, b))
    out = sys.stdout
    out.write("/* generated by tools/mkfold.py - do not edit */\n")
    out.write("#define FOLD_COUNT %d\n" % len(rows))
    out.write("static const uint16_t fold_cp[FOLD_COUNT] = {\n")
    for i in range(0, len(rows), 10):
        out.write("\t" + ", ".join("0x%04x" % r[0] for r in rows[i:i + 10]) + ",\n")
    out.write("};\n")
    out.write("/* length byte then up to 6 UTF-8 bytes */\n")
    out.write("static const uint8_t fold_out[FOLD_COUNT][7] = {\n")
    for cp, b in rows:
        vals = [len(b)] + list(b) + [0] * (6 - len(b))
        out.write("\t{" + ", ".join(str(v) for v in vals) + "},\n")
    out.write("};\n")


if __name__ == "__main__":
    main()
